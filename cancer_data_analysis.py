X_train_s, X_test_s, y_train_s, y_test_s = train_test_split(
    X,
    y_severity,
    test_size=0.2,
    random_state=40
)

# Hyperparameter grid
param_grid = {
    'n_estimators': [100, 200],
    'max_depth': [5, 10, None],
    'min_samples_split': [2, 5],
    'min_samples_leaf': [1, 2]
}

# Model
model = RandomForestRegressor(random_state=40)

# Grid Search
GSC = GridSearchCV(
    estimator=model,
    param_grid=param_grid,
    cv=3,
    scoring='r2',
    n_jobs=-1
)

# Train
